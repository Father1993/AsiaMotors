// Usage: node scripts/generate-brand-assets.mjs /absolute/path/to/asiamotors-logo.png
import { createHash } from 'node:crypto'
import { readFile, writeFile, rm, readdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

if (!process.argv[2]) throw new Error('Pass the path to the approved logo PNG')
const source = await readFile(process.argv[2])
const metadata = await sharp(source).metadata()
if (metadata.width !== 1536 || metadata.height !== 1024)
    throw new Error('Expected the approved 1536×1024 logo; review the emblem region and component dimensions for a different source')
const revision = createHash('sha256').update(source)
    .update(await readFile(new URL(import.meta.url))).digest('hex').slice(0, 12)
const root = new URL('../', import.meta.url)
const write = (path, data) => writeFile(new URL(path, root), data)
const background = '#111827'

// Preserve the entire approved artwork and its transparency. Never crop or stretch it.
const logo = await sharp(source).resize({ width: 768, withoutEnlargement: true })
    .webp({ quality: 92, effort: 6 }).toBuffer({ resolveWithObject: true })
const logoPath = `/img/asiamotors-logo-${revision}.webp`
await write(`public${logoPath}`, logo.data)
for (const name of await readdir(new URL('public/img/', root))) {
    if (/^asiamotors-logo(?:-[0-9a-f]{12})?\.webp$/.test(name) && `/img/${name}` !== logoPath)
        await rm(new URL(`public/img/${name}`, root))
}
// Retain the previous public PNG URL for existing external references.
await write('public/img/asia-motors-logo.png', await sharp(source)
    .resize({ width: 768, withoutEnlargement: true }).png({ compressionLevel: 9 }).toBuffer())

const icons = new Map()
for (const size of [16, 32, 48, 180, 192, 512]) {
    // Small favicons use the intact emblem above the wordmark so the mark stays legible.
    const image = sharp(source)
    if (size <= 48) image.extract({ left: 256, top: 64, width: 1024, height: 704 })
    icons.set(size, await image.resize(size, size, { fit: 'contain', background })
        .flatten({ background }).png({ compressionLevel: 9 }).toBuffer())
}
for (const [path, size] of [
    ['img/favicon-16x16.png', 16], ['img/favicon-32x32.png', 32],
    ['img/apple-touch-icon.png', 180],
    ['img/android-chrome-192x192.png', 192], ['img/android-chrome-512x512.png', 512],
    ['pwa/manager-180.png', 180], ['pwa/manager-192.png', 192], ['pwa/manager-512.png', 512],
]) await write(`public/${path}`, icons.get(size))

// ICO directory with correctly sized PNG frames, supported by current browsers.
const sizes = [16, 32, 48]
const directory = Buffer.alloc(6 + sizes.length * 16)
directory.writeUInt16LE(1, 2)
directory.writeUInt16LE(sizes.length, 4)
let offset = directory.length
for (const [index, size] of sizes.entries()) {
    const entry = 6 + index * 16
    directory[entry] = size
    directory[entry + 1] = size
    directory.writeUInt16LE(1, entry + 4)
    directory.writeUInt16LE(32, entry + 6)
    directory.writeUInt32LE(icons.get(size).length, entry + 8)
    directory.writeUInt32LE(offset, entry + 12)
    offset += icons.get(size).length
}
await write('public/img/favicon.ico', Buffer.concat([directory, ...sizes.map(size => icons.get(size))]))
await rm(new URL('public/pwa/manager.svg', root), { force: true })

const paths = {
    favicon: '/img/favicon.ico', favicon16: '/img/favicon-16x16.png', favicon32: '/img/favicon-32x32.png',
    apple: '/img/apple-touch-icon.png', icon192: '/img/android-chrome-192x192.png', icon512: '/img/android-chrome-512x512.png',
    managerApple: '/pwa/manager-180.png', manager192: '/pwa/manager-192.png', manager512: '/pwa/manager-512.png',
}
await write('shared/constants/branding.ts', `// Generated by scripts/generate-brand-assets.mjs from the approved logo.\n` +
    `export const BRAND_LOGO = ${JSON.stringify({ src: logoPath, width: logo.info.width, height: logo.info.height, alt: 'AsiaMotors' }, null, 4)} as const\n\n` +
    `export const BRAND_ICONS = ${JSON.stringify(Object.fromEntries(Object.entries(paths).map(([key, path]) => [key, `${path}?v=${revision}`])), null, 4)} as const\n\n` +
    `export const BRAND_FAVICONS = [\n` +
    `    { url: BRAND_ICONS.favicon, sizes: '16x16 32x32 48x48', type: 'image/x-icon' },\n` +
    `    { url: BRAND_ICONS.favicon16, sizes: '16x16', type: 'image/png' },\n` +
    `    { url: BRAND_ICONS.favicon32, sizes: '32x32', type: 'image/png' },\n` +
    `]\n`)
console.log(`Brand assets generated from ${fileURLToPath(root)}: ${revision}, logo ${logo.info.width}×${logo.info.height}, ${logo.data.length} bytes`)
